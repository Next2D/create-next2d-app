        "preview:ios": `${BUILDER} --platform ios --env prd --preview`,
        "preview:android": `${BUILDER} --platform android --env prd --preview`,
        "preview:macos": `${BUILDER} --platform macos --env prd --preview`,
        "preview:windows": `${BUILDER} --platform windows --env prd --preview`,
        "preview:linux": `${BUILDER} --platform linux --env prd --preview`,
        "open:ios": `${BUILDER} --platform ios --env prd --open`,
        "open:android": `${BUILDER} --platform android --env prd --open`,
        "open:xbox": `${BUILDER} --platform xbox --env prd --open`,
        "build:web": `${BUILDER} --platform web --env prd`,
        "build:ios": `${BUILDER} --platform ios --env prd --build`,
        "build:android": `${BUILDER} --platform android --env prd --build`,
        "build:xbox": `${BUILDER} --platform xbox --env prd`,
